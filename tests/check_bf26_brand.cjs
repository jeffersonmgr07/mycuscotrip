"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname,"..");
const read = p => fs.readFileSync(path.join(root,p),"utf8");
const landing = read("black-friday.html");
const css = read("assets/css/black-friday-2026.css");
const headerCss = read("assets/css/header.css");
const footerCss = read("assets/css/footer.css");
const claim = read("assets/js/black-friday-claim.js");
const badgeHtml = read("assets/js/components/black-friday-badge.js");
const badgeCss = read("assets/css/black-friday-badge.css");
const backend = read("google-apps-script/BlackFriday2026.gs");
assert.doesNotMatch(landing,/bf-topline|bf-destinations/,"no ticker or destination chips");
assert.match(landing,/Los cupones son válidos para una sola compra.*tiempo limitado/);
assert.match(landing,/id="header-container"/);
assert.match(landing,/id="footer-container"/);
assert.match(landing,/id="bf-country-trigger"/);
assert.doesNotMatch(landing,/fa-magnifying-glass/,"no magnifying glass");
assert.doesNotMatch(css,/\.mct-black-friday #header-container \.header/,"do not override shared header");
assert.doesNotMatch(css,/\.mct-black-friday #footer-container \.footer/,"do not override shared footer");
assert.doesNotMatch(css,/bf-ticker/,"no leftover ticker CSS");
assert.match(css,/machu-picchu-hero\.jpg/);
assert.ok(fs.existsSync(path.join(root,"assets/img/machu-picchu/machu-picchu-hero.jpg")),"hero image must exist");
assert.match(css,/@keyframes bf-machu-float/);
assert.match(css,/@keyframes bf-border-shift/);
assert.match(css,/@media\(max-width:900px\)\s*\{[\s\S]*?#bf-main \.bf-card \{order:1\}[\s\S]*?#bf-main \.bf-editorial \{order:2;padding-top:0\}/, "mobile form is shown before promotional message");
assert.match(headerCss, /background: #042d1d;/, "shared desktop/mobile header has darker brand green");
assert.match(headerCss, /background: rgba\(4, 45, 29, 0\.96\);/, "sticky header also darkened");
assert.match(footerCss, /background: #003521;/, "shared footer darkened for all viewports");
assert.match(css,/#bf-main \.bf-country-option/);
assert.doesNotMatch(css, /input:not\(\[type="checkbox"\]\),\s*\/\*/, "malformed input selector must not recur");
assert.match(css, /input:not\(\[type="checkbox"\]\):not\(\[type="hidden"\]\)\s*\{[\s\S]*?display:block/, "visible fields must have block styles");
assert.match(css, /\.bf-card \.bf-fields > \* \{min-width:0\}/, "fields should not overflow their grid columns");
assert.match(css, /\.bf-country-options \{max-height:230px/, "country options must remain scrollable");

assert.match(claim,/bf-country-trigger/);
assert.match(claim,/createDocumentFragment/);
assert.match(badgeHtml,/mct-bf26-time/);
assert.match(badgeCss,/#eb3bae/);
assert.match(badgeCss,/@keyframes mctBfPulse/);
assert.match(badgeCss,/background:#ffffff/);
assert.match(backend,/function mctBfEmailHtml_/);
assert.match(backend,/htmlBody:mctBfEmailHtml_\('otp'/);
assert.match(backend,/htmlBody:mctBfEmailHtml_\('coupon'/);
assert.match(backend,/mycuscotrip\.com\/assets\/img\/logos\/Logo1\.png/);
console.log("PASS: MCT brand header/footer, Machu Picchu animation, custom country selector, fuchsia badge and branded emails.");
